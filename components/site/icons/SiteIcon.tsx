export function SiteIcon({
                             name,
                             className,
                         }: SiteIconProps) {
    const icons = useSiteIcons();

    const svg = icons[name] || defaultIcons[name];

    if (!svg) {
        return null;
    }

    const svgWithClass = svg.replace(
        '<svg',
        `<svg class="site-icon site-icon--${name}${className ? ` ${className}` : ''}"`
    );

    return parse(svgWithClass);
}